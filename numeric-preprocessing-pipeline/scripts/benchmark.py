"""Stage-by-stage benchmark on synthetic data; writes reports/benchmark.md.

Honest memory accounting: per-stage RSS deltas come from
``getrusage(RUSAGE_SELF).ru_maxrss`` — a process-level HIGH-WATER MARK. It is
monotonic, so a stage that allocates less than a previous peak shows a ~0
delta, and the reported per-stage numbers are lower bounds for the true
per-stage footprint. The final peak is exact.

Usage:
    python scripts/benchmark.py --sizes 10000 100000 1000000 --out reports
"""

from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from numprep import audit as audit_mod
from numprep import clean as clean_mod
from numprep import contracts
from numprep import ingest as ingest_mod
from numprep import pipeline as pipeline_mod
from numprep import split as split_mod
from numprep.config import load_config
from numprep.jsonlog import peak_rss_mb, setup_logging
from numprep.seed import set_global_seed
from numprep.synthesize import generate_messy_dataset, save_messy_csv


def benchmark_size(rows: int, seed: int, workdir: Path, logger) -> list[dict[str, object]]:
    """Run every stage once for a given row count; return per-stage records."""
    set_global_seed(seed)
    cfg = load_config()
    cfg.input.paths = [str(workdir / f"synthetic_{rows}.csv")]
    cfg.output.directory = workdir / f"out_{rows}"
    cfg.target.column = "target"
    cfg.validation.input.max_null_rate = {"*": 0.5, "all_null_col": 1.0, "mostly_null": 0.99}
    cfg.run.downcast = "off"  # keep the benchmark focused on stage cost

    records: list[dict[str, object]] = []

    def record(stage: str, started: float) -> None:
        records.append(
            {
                "stage": stage,
                "rows": rows,
                "seconds": round(time.perf_counter() - started, 3),
                "peak_rss_mb": round(peak_rss_mb(), 1),
            }
        )

    started = time.perf_counter()
    ingest_result = ingest_mod.ingest(cfg, Path(cfg.output.directory), logger)
    record("ingest", started)

    started = time.perf_counter()
    contracts.validate_input_contract(ingest_result.frame, cfg)
    record("validate_input", started)

    started = time.perf_counter()
    audit_mod.audit_frame(ingest_result.frame, cfg)
    record("audit", started)

    started = time.perf_counter()
    cleaned, _ = clean_mod.clean_stateless(ingest_result.frame, cfg)
    record("clean", started)

    started = time.perf_counter()
    frame_pd = cleaned.to_pandas()
    record("to_pandas", started)

    started = time.perf_counter()
    split_result = split_mod.split_data(frame_pd, cfg)
    record("split", started)

    started = time.perf_counter()
    pipe = pipeline_mod.build_pipeline(cfg)
    pipeline_mod.fit_preprocessor(pipe, split_result.train, cfg)
    record("fit", started)

    started = time.perf_counter()
    for name, part in split_result.partitions().items():
        pipeline_mod.transform_partition(pipe, part, cfg, name)
    record("transform", started)

    return records


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sizes", type=int, nargs="+", default=[10_000, 100_000])
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--out", type=Path, default=Path("reports"))
    parser.add_argument("--log-level", default="ERROR")
    args = parser.parse_args()

    workdir = Path(".benchmark")
    workdir.mkdir(exist_ok=True)
    logger = setup_logging(args.log_level)

    all_records: list[dict[str, object]] = []
    for rows in args.sizes:
        csv_path = workdir / f"synthetic_{rows}.csv"
        if not csv_path.exists():
            print(f"[benchmark] generating {rows:,} rows ...", flush=True)
            save_messy_csv(generate_messy_dataset(rows=rows, seed=args.seed), csv_path)
        print(f"[benchmark] running {rows:,} rows ...", flush=True)
        all_records.extend(benchmark_size(rows, args.seed, workdir, logger))

    lines: list[str] = []
    lines.append("# Benchmark Report")
    lines.append("")
    lines.append(f"*Generated by `scripts/benchmark.py` · seed {args.seed}*")
    lines.append("")
    lines.append("| rows | stage | seconds | cumulative peak RSS (MiB) |")
    lines.append("|---:|---|---:|---:|")
    for record in all_records:
        lines.append(
            f"| {record['rows']:,} | {record['stage']} "
            f"| {record['seconds']} | {record['peak_rss_mb']} |"
        )
    lines.append("")
    lines.append(
        "**Honest memory note:** the RSS column is the process-level high-water mark "
        "(`getrusage(ru_maxrss)`) — monotonic across stages, so per-stage deltas "
        "under-report for stages allocating less than an earlier peak. The final row "
        "is the true total peak."
    )
    lines.append("")
    lines.append(
        "**Scaling limits (stated honestly):** ingest/audit/clean run on Polars with "
        "streaming collects and sampled approximations (correlations, duplicate scan) "
        "and handle data beyond RAM for *text ingest*; the fitted sklearn stage "
        "(impute/select/scale) is in-memory — datasets must fit in RAM *after* the "
        "string→numeric snapshot conversion. Sampling parameters live in the config "
        "(`audit.*`, `preprocessing.selection.sample_size`)."
    )
    lines.append("")

    args.out.mkdir(parents=True, exist_ok=True)
    target = args.out / "benchmark.md"
    target.write_text("\n".join(lines), encoding="utf-8")
    print(f"[benchmark] wrote {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
